"""Tests for the MCP server code generator."""

import ast
import os

from oxvara.codegen import generate_server
from oxvara.parser import load_spec_file

EXAMPLE = os.path.join(
    os.path.dirname(__file__), "..", "examples", "petstore.yaml"
)


def _source():
    estate = load_spec_file(EXAMPLE)
    return generate_server(estate, filename="petserver.py")


def test_generated_source_is_valid_python():
    ast.parse(_source())


def test_generated_source_registers_three_tools():
    src = _source()
    assert src.count("@mcp.tool()") == 3
    assert "def petstore_list_pets(" in src
    assert "def petstore_create_pet(" in src
    assert "def petstore_get_pet(" in src


def test_generated_source_carries_inherited_policy():
    src = _source()
    assert '"petstore_create_pet": (10, 60)' in src
    assert '"petstore_list_pets": (100, 60)' in src
    assert "X-API-Key" in src
    assert "OXVARA_API_KEY" in src
    assert "Rate limit: 10/minute" in src


def test_generated_source_mentions_regeneration():
    src = _source()
    assert "generated by Oxvara" in src
    assert "Do not edit by hand" in src
    assert 'mcp.run()' in src


def test_path_parameter_is_substituted_into_url():
    src = _source()
    assert 'url = f"{BASE_URL}/pets/{petId}"' in src
