"""Tests for the MCP server code generator."""

import ast
import os

from avouch.codegen import generate_server
from avouch.parser import load_spec_file

EXAMPLE = os.path.join(
    os.path.dirname(__file__), "..", "examples", "petstore.yaml"
)


def _source():
    estate = load_spec_file(EXAMPLE)
    return generate_server(estate, filename="petserver.py")


def test_generated_source_is_valid_python():
    ast.parse(_source())


def test_generated_source_registers_three_tools():
    src = _source()
    assert src.count("@mcp.tool()") == 3
    assert "def petstore_list_pets(" in src
    assert "def petstore_create_pet(" in src
    assert "def petstore_get_pet(" in src


def test_generated_source_carries_inherited_policy():
    src = _source()
    assert '"petstore_create_pet": (10, 60)' in src
    assert '"petstore_list_pets": (100, 60)' in src
    assert "X-API-Key" in src
    assert "AVOUCH_API_KEY" in src
    assert "Rate limit: 10/minute" in src


def test_generated_source_mentions_regeneration():
    src = _source()
    assert "generated by Avouch" in src
    assert "Do not edit by hand" in src
    assert 'mcp.run()' in src


def test_path_parameter_is_substituted_into_url():
    src = _source()
    assert 'url = BASE_URL + _fill_path("/pets/{petId}", {"petId": petId})' in src


def test_each_tool_gets_its_own_auth_call():
    from avouch.models import (
        ApiEstate,
        AuthPolicy,
        Endpoint,
        Policy,
    )

    estate = ApiEstate(
        title="Mixed", slug="mixed", version="1", base_url="https://x.example"
    )
    estate.endpoints.append(
        Endpoint(
            operation_id="a",
            tool_name="mixed_a",
            method="GET",
            path="/a",
            summary="a",
            description="",
            policy=Policy(auth=AuthPolicy(kind="apiKey", name="X-Key", location="header")),
        )
    )
    estate.endpoints.append(
        Endpoint(
            operation_id="b",
            tool_name="mixed_b",
            method="GET",
            path="/b",
            summary="b",
            description="",
            policy=Policy(auth=AuthPolicy(kind="bearer")),
        )
    )
    src = generate_server(estate, filename="mixed.py")
    ast.parse(src)
    assert 'headers.update(_auth_headers("apiKey", "X-Key", "header"))' in src
    assert 'headers.update(_auth_headers("bearer", "", "header"))' in src
    # the old bug generated one shared _auth_headers() call for every tool
    assert "_auth_headers()" not in src


