def safe_identifier(name: str, taken: set[str]) -> str:
    """Map any wire name to a unique, non-shadowing Python identifier."""
    ident = re.sub(r"\W", "_", name, flags=re.ASCII) or "arg"
    if ident[0].isdigit():
        ident = "_" + ident
    if keyword.iskeyword(ident) or ident in _RESERVED or ident.startswith("_ox"):
        ident += "_"
    base, n = ident, 2
    while ident in taken:
        ident = f"{base}_{n}"
        n += 1
    taken.add(ident)
    return ident


def tool_names(estate: ApiEstate) -> list[str]:
    """Unique MCP tool names, one per endpoint, in endpoint order.

    MCP tool names are limited to letters, digits, '_' and '-'. When two
    gateways expose the same name, both get their gateway kind as a
    prefix (``apigee_petstore_get_pet``, ``apim_petstore_get_pet``).
    """
    raw = [re.sub(r"[^A-Za-z0-9_-]", "_", ep.tool_name) for ep in estate.endpoints]
    sources_by_name: dict[str, set[str]] = {}
    for ep, name in zip(estate.endpoints, raw):
        sources_by_name.setdefault(name, set()).add(ep.source)
    seen: set[str] = set()
    names = []
    for ep, base in zip(estate.endpoints, raw):
        if len(sources_by_name[base]) > 1 and ep.source:
            base = f"{ep.source.split(':')[0]}_{base}"
        base = base[:60] or "tool"
        name, n = base, 2
        while name in seen:
            name = f"{base}_{n}"
            n += 1
        seen.add(name)
        names.append(name)
    return names


def tool_description(ep: Endpoint) -> str:
    """The description an agent sees: spec text plus inherited policy."""
    lines = [ep.summary or ep.tool_name]
    if ep.description and ep.description != ep.summary:
        lines += ["", ep.description]
    policy_bits = []
    auth = ep.policy.auth
    if auth.kind != "none":
        policy_bits.append(f"Auth: {auth.kind}")
    if ep.policy.rate_limit:
        rl = ep.policy.rate_limit
        policy_bits.append(f"Rate limit: {rl.requests}/{rl.per}")
    if policy_bits:
        lines += ["", "Inherited policy: " + "; ".join(policy_bits) + "."]
    return "\n".join(lines)


def _generate_tool(estate: ApiEstate, ep: Endpoint, tool_name: str, func: str) -> str:
    taken: set[str] = set()
    # (wire name, identifier, annotation, location, required)
    args: list[tuple[str, str, str, str, bool]] = []
    for p in ep.parameters:
        args.append((p.name, safe_identifier(p.name, taken),
                     PY_TYPES.get(p.schema_type, "str"), p.location, p.required))
    for b in ep.body_properties:
        args.append((b.name, safe_identifier(b.name, taken),
                     PY_TYPES.get(b.schema_type, "str"), "body", b.required))
    if ep.body_raw:
        args.append(("body", safe_identifier("body", taken), "str", "raw", False))

    ordered = [a for a in args if a[4]] + [a for a in args if not a[4]]
    sig = ", ".join(
        f"{ident}: {ann}" if req else f"{ident}: {ann} = None"
        for _, ident, ann, _, req in ordered
    )
    read_only, destructive, idempotent = _ANNOTATIONS.get(
        ep.method, (False, True, False)
    )
    t = repr(tool_name)
    decorator = (
        f"@mcp.tool(\n    name={t},\n    description={tool_description(ep)!r},\n"
        f"    annotations=ToolAnnotations(readOnlyHint={read_only}, "
        f"destructiveHint={destructive}, idempotentHint={idempotent}, "
        "openWorldHint=True),\n)"
    )
    out = [
        decorator,
        f"def {func}({sig}) -> str:",
        f"    _check_rate_limit({t})",
    ]
    audit_args = ", ".join(f"{wire!r}: {ident}" for wire, ident, *_ in ordered)
    out.append(f"    _audit('call', {t}, args=_redact({{{audit_args}}}))")
    auth = ep.policy.auth
    out.append("    _ox_headers = {'Accept': 'application/json'}")
    out.append(
        f"    _ox_headers.update(_auth_headers({auth.kind!r}, "
        f"{auth.name!r}, {auth.location!r}))"
    )
    for wire, ident, _, loc, req in args:
        if loc == "header":
            guard = "" if req else f"if {ident} is not None:\n        "
            out.append(f"    {guard}_ox_headers[{wire!r}] = str({ident})")

    query = [a for a in args if a[3] == "query"]
    key_in_query = auth.kind == "apiKey" and auth.location == "query"
    if query or key_in_query:
        out.append("    _ox_params = {}")
        for wire, ident, _, _, req in query:
            guard = "" if req else f"if {ident} is not None:\n        "
            out.append(f"    {guard}_ox_params[{wire!r}] = {ident}")
        if key_in_query:
            out.append("    _ox_key = os.environ.get('OXVARA_API_KEY', '')")
            out.append(f"    if _ox_key:\n        _ox_params[{auth.name!r}] = _ox_key")
    else:
        out.append("    _ox_params = None")

    body = [a for a in args if a[3] == "body"]
    raw = [a for a in args if a[3] == "raw"]
    if body:
        out.append("    _ox_payload = {}")
        for wire, ident, _, _, req in body:
            guard = "" if req else f"if {ident} is not None:\n        "
            out.append(f"    {guard}_ox_payload[{wire!r}] = {ident}")
    elif raw:
        ident = raw[0][1]
        out.append(f"    _ox_payload = json.loads({ident}) if {ident} else None")
    else:
        out.append("    _ox_payload = None")

    path_values = ", ".join(
        f"{wire!r}: {ident}" for wire, ident, _, loc, _ in args if loc == "path"
    )
    base = estate.base_for(ep)
    base_expr = "BASE_URL" if base == estate.base_url else repr(base)
    out.append(
        f"    _ox_url = {base_expr} + _fill_path({ep.path!r}, {{{path_values}}})"
    )
    out.append(
        "    _ox_resp = requests.request(\n"
        f"        {ep.method!r}, _ox_url, headers=_ox_headers, params=_ox_params,\n"
        f"        json=_ox_payload, timeout={int(ep.policy.timeout)},\n"
        "    )"
    )
    out.append(f"    _audit('response', {t}, status=_ox_resp.status_code)")
    out.append("    _ox_resp.raise_for_status()")
    out.append(f"    return _guard_response({t}, _ox_resp.text)")
    out.append("\n")
    return "\n".join(out)


def _doc_safe(text: str) -> str:
    return re.sub(r"[^\w .,:@/+-]", "_", text)[:120]


def generate_server(estate: ApiEstate, filename: str = "server.py") -> str:
    """Render the full MCP server module for an estate."""
    names = tool_names(estate)
    parts = [
        HEADER.format(
            title=_doc_safe(estate.title),
            version=_doc_safe(__version__),
            filename=_doc_safe(filename),
            version_lit=repr(__version__),
            source_lit=repr(f"{estate.kind}:{estate.slug}@{estate.version}"),
            base_url_lit=repr(estate.base_url),
        )
    ]

    entries = []
    for ep, name in zip(estate.endpoints, names):
        rl = ep.policy.rate_limit
        if rl:
            entries.append(f"    {name!r}: ({int(rl.requests)}, {rl.window_seconds()}),")
    parts.append(RATE_LIMITER.format(entries="\n".join(entries)))
    parts.append(RUNTIME)
    parts.append(f"mcp = FastMCP({estate.slug!r})\n\n\n")

    funcs: set[str] = set()
    for ep, name in zip(estate.endpoints, names):
        func = safe_identifier(name.replace("-", "_"), funcs)
        parts.append(_generate_tool(estate, ep, name, func))

    parts.append(FOOTER.lstrip("\n"))
    return "".join(parts)


def write_server(estate: ApiEstate, path: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(generate_server(estate, filename=os.path.basename(path)))
