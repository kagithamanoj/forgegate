"""Generate a runnable MCP server from a normalized ApiEstate.

The emitted module is self-contained: it builds a FastMCP server whose
tools call the gateway endpoints, inject the inherited auth credentials,
and enforce the inherited rate limits client-side before any request
leaves the process.

Everything taken from an imported spec (titles, URLs, parameter names,
descriptions) is untrusted input. It reaches the generated source only
as ``repr()`` literals or as sanitized Python identifiers, so a hostile
spec cannot inject code into the server it compiles to.
"""

from __future__ import annotations

import keyword
import os
import re

from . import __version__
from .models import ApiEstate, Endpoint

PY_TYPES = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
}

# Names a tool parameter must not shadow inside the generated function.
_RESERVED = {
    "json", "os", "re", "sys", "time", "urllib", "requests", "mcp",
    "BASE_URL", "ToolAnnotations", "FastMCP",
}

# MCP tool annotations derived from HTTP semantics. They are hints for
# clients (auto-approve reads, confirm destructive writes), not security
# controls: the gateway policy is the control.
_ANNOTATIONS = {
    "GET": (True, False, True),
    "HEAD": (True, False, True),
    "OPTIONS": (True, False, True),
    "PUT": (False, True, True),
    "DELETE": (False, True, True),
    "PATCH": (False, True, False),
    "POST": (False, False, False),
}

