"""Generate a runnable MCP server from a normalized ApiEstate.

The emitted module is self-contained: it builds a FastMCP server whose
tools call the original REST endpoints, inject the inherited auth
credentials, and enforce the inherited rate limits client-side before
any request leaves the process.
"""

from __future__ import annotations

from . import __version__
from .models import ApiEstate, AuthPolicy, Endpoint

PY_TYPES = {
    "string": "str",
    "integer": "int",
    "number": "float",
    "boolean": "bool",
}

HEADER = '''"""MCP server for {title}, generated by Oxvara {version}.

Do not edit by hand. Regenerate with:

    oxvara compile <spec> -o {filename}

Source spec: {title} {spec_version}
Base URL: {base_url}
"""

import json
import os
import time

import requests
from mcp.server.fastmcp import FastMCP

OXVARA_VERSION = "{version}"
BASE_URL = "{base_url}"


class OxvaraError(Exception):
    """Base error for generated server failures."""


class RateLimitExceeded(OxvaraError):
    """Raised when a tool's client side rate budget is exhausted."""


'''

RATE_LIMITER = '''_RATE_LIMITS = {{
{entries}
}}
_buckets = {{}}


def _check_rate_limit(tool_name):
    """Enforce the per-tool rate budget inherited from the API estate."""
    spec = _RATE_LIMITS.get(tool_name)
    if not spec:
        return
    limit, window = spec
    now = time.monotonic()
    bucket = _buckets.get(tool_name)
    if bucket is None or now >= bucket["reset_at"]:
        bucket = {{"remaining": limit, "reset_at": now + window}}
    if bucket["remaining"] <= 0:
        raise RateLimitExceeded(
            "%s: rate budget exhausted (%d requests per %ds)"
            % (tool_name, limit, window)
        )
    bucket["remaining"] -= 1
    _buckets[tool_name] = bucket


'''

FOOTER = '''

if __name__ == "__main__":
    mcp.run()
'''


def _auth_helper(auth: AuthPolicy) -> str:
    if auth.kind == "apiKey":
        lines = [
            "def _auth_headers():",
            f'    """Inject the inherited {auth.name} API key."""',
            f'    key = os.environ.get("OXVARA_API_KEY", "")',
        ]
        if auth.location == "query":
            lines.append("    return {}  # key is sent as a query param, see below")
        else:
            lines.append(f'    return {{"{auth.name}": key}} if key else {{}}')
        return "\n".join(lines) + "\n\n\n"
    if auth.kind == "bearer":
        return (
            "def _auth_headers():\n"
            '    """Inject the inherited bearer token."""\n'
            '    token = os.environ.get("OXVARA_BEARER_TOKEN", "")\n'
            '    return {"Authorization": "Bearer " + token} if token else {}\n'
            "\n\n"
        )
    if auth.kind == "oauth2":
        return (
            "def _auth_headers():\n"
            '    """OAuth2 is declared by the estate but not wired up yet."""\n'
            "    raise NotImplementedError(\n"
            '        "oauth2 token acquisition is not implemented in this "\n'
            '        "prototype; see docs/ARCHITECTURE.md"\n'
            "    )\n"
            "\n\n"
        )
    return "def _auth_headers():\n    return {}\n\n\n"


def _unique_tool_names(estate: ApiEstate) -> dict[str, str]:
    seen: dict[str, int] = {}
    mapping: dict[str, str] = {}
    for ep in estate.endpoints:
        base = ep.tool_name
        n = seen.get(base, 0)
        seen[base] = n + 1
        mapping[ep.operation_id] = base if n == 0 else f"{base}_{n}"
    return mapping


def _docstring(ep: Endpoint) -> str:
    lines = [ep.summary or ep.tool_name]
    if ep.description and ep.description != ep.summary:
        lines += ["", ep.description]
    policy_bits = []
    auth = ep.policy.auth
    if auth.kind != "none":
        policy_bits.append(f"Auth: {auth.kind}")
    if ep.policy.rate_limit:
        rl = ep.policy.rate_limit
        policy_bits.append(f"Rate limit: {rl.requests}/{rl.per}")
    if policy_bits:
        lines += ["", "Inherited policy: " + "; ".join(policy_bits) + "."]
    text = "\n".join(lines).replace('"""', "'''")
    return f'    """{text}"""\n'


def _generate_tool(ep: Endpoint, tool_name: str) -> str:
    # Signature: required params first, then optional ones.
    required, optional = [], []
    for p in ep.parameters:
        ann = PY_TYPES.get(p.schema_type, "str")
        (required if p.required else optional).append((p.name, ann))
    body_props = []
    for b in ep.body_properties:
        ann = PY_TYPES.get(b.schema_type, "str")
        (required if b.required else optional).append((b.name, ann))
        body_props.append((b.name, b.required))
    if ep.body_raw:
        optional.append(("body", "str"))

    sig_parts = [f"{n}: {a}" for n, a in required]
    sig_parts += [f"{n}: {a} = None" for n, a in optional]
    sig = ", ".join(sig_parts)

    out = [f"@mcp.tool()\ndef {tool_name}({sig}) -> str:"]
    out.append(_docstring(ep).rstrip("\n"))
    out.append(f'    _check_rate_limit("{tool_name}")')
    out.append('    headers = {"Accept": "application/json"}')
    out.append("    headers.update(_auth_headers())")

    query_params = [p for p in ep.parameters if p.location == "query"]
    if query_params:
        out.append("    params = {}")
        for p in query_params:
            if p.required:
                out.append(f'    params["{p.name}"] = {p.name}')
            else:
                out.append(f"    if {p.name} is not None:")
                out.append(f'        params["{p.name}"] = {p.name}')
        if ep.policy.auth.kind == "apiKey" and ep.policy.auth.location == "query":
            out.append(
                '    _key = os.environ.get("OXVARA_API_KEY", "")\n'
                f'    if _key:\n        params["{ep.policy.auth.name}"] = _key'
            )
    else:
        out.append("    params = None")

    if body_props:
        out.append("    payload = {}")
        for name, req in body_props:
            if req:
                out.append(f'    payload["{name}"] = {name}')
            else:
                out.append(f"    if {name} is not None:")
                out.append(f'        payload["{name}"] = {name}')
    elif ep.body_raw:
        out.append("    payload = json.loads(body) if body else None")
    else:
        out.append("    payload = None")

    out.append(f'    url = f"{{BASE_URL}}{ep.path}"')
    out.append(
        "    resp = requests.request(\n"
        f'        "{ep.method}", url, headers=headers, params=params,\n'
        f"        json=payload, timeout={ep.policy.timeout},\n"
        "    )"
    )
    out.append("    resp.raise_for_status()")
    out.append("    return resp.text")
    out.append("\n")
    return "\n".join(out)


def generate_server(estate: ApiEstate, filename: str = "server.py") -> str:
    """Render the full MCP server module for an estate."""
    names = _unique_tool_names(estate)
    parts = [
        HEADER.format(
            title=estate.title,
            version=__version__,
            filename=filename,
            spec_version=estate.version,
            base_url=estate.base_url,
        )
    ]

    entries = []
    for ep in estate.endpoints:
        rl = ep.policy.rate_limit
        if rl:
            entries.append(
                f'    "{names[ep.operation_id]}": '
                f"({rl.requests}, {rl.window_seconds()}),"
            )
    parts.append(RATE_LIMITER.format(entries="\n".join(entries)))

    auth = estate.endpoints[0].policy.auth if estate.endpoints else AuthPolicy()
    parts.append(_auth_helper(auth))
    parts.append(f'mcp = FastMCP("{estate.slug}")\n\n\n')

    for ep in estate.endpoints:
        parts.append(_generate_tool(ep, names[ep.operation_id]))

    parts.append(FOOTER.lstrip("\n"))
    return "".join(parts)


def write_server(estate: ApiEstate, path: str) -> None:
    import os

    with open(path, "w", encoding="utf-8") as fh:
        fh.write(generate_server(estate, filename=os.path.basename(path)))
