FOOTER = '''

if __name__ == "__main__":
    mcp.run()
'''


def _q(value: str) -> str:
    """Escape a string for embedding in a double-quoted Python literal."""
    return value.replace("\\", "\\\\").replace('"', '\\"')


AUTH_DISPATCH = '''def _auth_headers(kind, name, location):
    """Inject the credentials inherited from the API estate for one tool.

    Credentials always come from the environment, never from the spec:
    OXVARA_API_KEY, OXVARA_BEARER_TOKEN, OXVARA_BASIC_CREDENTIALS,
    and for oauth2 OXVARA_OAUTH_ACCESS_TOKEN (delegated token passthrough)
    or OXVARA_OAUTH_TOKEN_URL/CLIENT_ID/CLIENT_SECRET[/SCOPE] (client
    credentials grant, cached until expiry).
    """
    if kind == "apiKey":
        key = os.environ.get("OXVARA_API_KEY", "")
        if not key:
            return {}
        if location == "query":
            return {}  # sent as a query param, see the tool body
        return {name: key}
    if kind == "bearer":
        token = os.environ.get("OXVARA_BEARER_TOKEN", "")
        return {"Authorization": "Bearer " + token} if token else {}
    if kind == "basic":
        creds = os.environ.get("OXVARA_BASIC_CREDENTIALS", "")
        return {"Authorization": "Basic " + creds} if creds else {}
    if kind == "oauth2":
        token = _oauth2_token()
        return {"Authorization": "Bearer " + token} if token else {}
    return {}


'''


OAUTH2 = '''_oauth_cache = {{"token": "", "expires_at": 0.0}}


def _oauth2_token():
    """Return a bearer token for oauth2 tools.

    Prefers a delegated token supplied by the caller (per-user identity)
    over the service's own client-credentials grant.
    """
    delegated = os.environ.get("OXVARA_OAUTH_ACCESS_TOKEN", "")
    if delegated:
        return delegated
    if _oauth_cache["token"] and time.time() < _oauth_cache["expires_at"] - 30:
        return _oauth_cache["token"]
    url = os.environ.get("OXVARA_OAUTH_TOKEN_URL", "")
    cid = os.environ.get("OXVARA_OAUTH_CLIENT_ID", "")
    secret = os.environ.get("OXVARA_OAUTH_CLIENT_SECRET", "")
    if not (url and cid and secret):
        raise OxvaraError(
            "oauth2 required: set OXVARA_OAUTH_ACCESS_TOKEN, or "
            "OXVARA_OAUTH_TOKEN_URL, OXVARA_OAUTH_CLIENT_ID and "
            "OXVARA_OAUTH_CLIENT_SECRET"
        )
    data = {{"grant_type": "client_credentials"}}
    scope = os.environ.get("OXVARA_OAUTH_SCOPE", "")
    if scope:
        data["scope"] = scope
    resp = requests.post(url, data=data, auth=(cid, secret), timeout=15)
    resp.raise_for_status()
    body = resp.json()
    _oauth_cache["token"] = body["access_token"]
    _oauth_cache["expires_at"] = time.time() + float(body.get("expires_in", 300))
    return _oauth_cache["token"]


'''

def _unique_tool_names(estate: ApiEstate) -> dict[str, str]:
    seen: dict[str, int] = {}
    mapping: dict[str, str] = {}
    for ep in estate.endpoints:
        base = ep.tool_name
        n = seen.get(base, 0)
        seen[base] = n + 1
        mapping[ep.operation_id] = base if n == 0 else f"{base}_{n}"
    return mapping


def _docstring(ep: Endpoint) -> str:
    lines = [ep.summary or ep.tool_name]
    if ep.description and ep.description != ep.summary:
        lines += ["", ep.description]
    policy_bits = []
    auth = ep.policy.auth
    if auth.kind != "none":
        policy_bits.append(f"Auth: {auth.kind}")
    if ep.policy.rate_limit:
        rl = ep.policy.rate_limit
        policy_bits.append(f"Rate limit: {rl.requests}/{rl.per}")
    if policy_bits:
        lines += ["", "Inherited policy: " + "; ".join(policy_bits) + "."]
    text = "\n".join(lines).replace('"""', "'''")
    return f'    """{text}"""\n'


def _generate_tool(ep: Endpoint, tool_name: str) -> str:
    # Signature: required params first, then optional ones.
    required, optional = [], []
    for p in ep.parameters:
        ann = PY_TYPES.get(p.schema_type, "str")
        (required if p.required else optional).append((p.name, ann))
    body_props = []
    for b in ep.body_properties:
        ann = PY_TYPES.get(b.schema_type, "str")
        (required if b.required else optional).append((b.name, ann))
        body_props.append((b.name, b.required))
    if ep.body_raw:
        optional.append(("body", "str"))

    sig_parts = [f"{n}: {a}" for n, a in required]
    sig_parts += [f"{n}: {a} = None" for n, a in optional]
    sig = ", ".join(sig_parts)

    out = [f"@mcp.tool()\ndef {tool_name}({sig}) -> str:"]
    out.append(_docstring(ep).rstrip("\n"))
    out.append(f'    _check_rate_limit("{tool_name}")')
    args = ", ".join(f'"{n}": {n}' for n, _ in required + optional)
    out.append(f'    _audit("call", "{tool_name}", args=_redact({{{args}}}))')
    out.append('    headers = {"Accept": "application/json"}')
    auth = ep.policy.auth
    out.append(
        f'    headers.update(_auth_headers("{_q(auth.kind)}", '
        f'"{_q(auth.name)}", "{_q(auth.location)}"))'
    )

    query_params = [p for p in ep.parameters if p.location == "query"]
    if query_params:
        out.append("    params = {}")
        for p in query_params:
            if p.required:
                out.append(f'    params["{p.name}"] = {p.name}')
            else:
                out.append(f"    if {p.name} is not None:")
                out.append(f'        params["{p.name}"] = {p.name}')
        if ep.policy.auth.kind == "apiKey" and ep.policy.auth.location == "query":
            out.append(
                '    _key = os.environ.get("OXVARA_API_KEY", "")\n'
                f'    if _key:\n        params["{ep.policy.auth.name}"] = _key'
            )
    else:
        out.append("    params = None")

    if body_props:
        out.append("    payload = {}")
        for name, req in body_props:
            if req:
                out.append(f'    payload["{name}"] = {name}')
            else:
                out.append(f"    if {name} is not None:")
                out.append(f'        payload["{name}"] = {name}')
    elif ep.body_raw:
        out.append("    payload = json.loads(body) if body else None")
    else:
        out.append("    payload = None")

    path_params = [p.name for p in ep.parameters if p.location == "path"]
    values = ", ".join(f'"{n}": {n}' for n in path_params)
    out.append(f'    url = BASE_URL + _fill_path("{_q(ep.path)}", {{{values}}})')
    out.append(
        "    resp = requests.request(\n"
        f'        "{ep.method}", url, headers=headers, params=params,\n'
        f"        json=payload, timeout={ep.policy.timeout},\n"
        "    )"
    )
    out.append(
        f'    _audit("response", "{tool_name}", status=resp.status_code)'
    )
    out.append("    resp.raise_for_status()")
    out.append(f'    return _guard_response("{tool_name}", resp.text)')
    out.append("\n")
    return "\n".join(out)


def generate_server(estate: ApiEstate, filename: str = "server.py") -> str:
    """Render the full MCP server module for an estate."""
    names = _unique_tool_names(estate)
    parts = [
        HEADER.format(
            title=estate.title,
            version=__version__,
            filename=filename,
            spec_version=estate.version,
            base_url=estate.base_url,
        )
    ]

    entries = []
    for ep in estate.endpoints:
        rl = ep.policy.rate_limit
        if rl:
            entries.append(
                f'    "{names[ep.operation_id]}": '
                f"({rl.requests}, {rl.window_seconds()}),"
            )
    parts.append(RATE_LIMITER.format(entries="\n".join(entries)))

    parts.append(AUDIT_AND_GUARDS.format())
    parts.append(OAUTH2.format())
    parts.append(AUTH_DISPATCH)
    parts.append(f'mcp = FastMCP("{estate.slug}")\n\n\n')

    for ep in estate.endpoints:
        parts.append(_generate_tool(ep, names[ep.operation_id]))

    parts.append(FOOTER.lstrip("\n"))
    return "".join(parts)


def write_server(estate: ApiEstate, path: str) -> None:
    import os

    with open(path, "w", encoding="utf-8") as fh:
        fh.write(generate_server(estate, filename=os.path.basename(path)))
